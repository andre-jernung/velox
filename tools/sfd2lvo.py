#!/usr/bin/env python3
"""Generate a vasm LVO include (_LVOName equ -offset) from an Amiga .sfd file.

usage: sfd2lvo.py input.sfd output.i
"""
import re
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    bias = 30
    offset = None
    last = None
    out = []
    varargs = False
    for raw in open(src, encoding="latin-1"):
        line = raw.strip()
        if not line or line.startswith("*"):
            continue
        if raw[0] in " \t":
            continue                # continuation of a multi-line prototype
        if line.startswith("=="):
            key, _, arg = line[2:].partition(" ")
            if key == "bias":
                bias = int(arg)
                offset = bias
            elif key == "reserve":
                offset = (offset or bias) + 6 * int(arg)
            elif key in ("varargs", "alias"):
                varargs = True      # next function shares the previous LVO
            elif key == "end":
                break
            continue
        m = re.search(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(", line)
        if not m:
            continue
        name = m.group(1)
        if varargs:
            varargs = False
            continue
        if offset is None:
            offset = bias
        out.append(f"_LVO{name}\tequ\t-{offset}\n")
        last = name
        offset += 6
    with open(dst, "w") as f:
        f.write(f"; generated by tools/sfd2lvo.py from {src.split('/')[-1]} - do not edit\n")
        f.writelines(out)


if __name__ == "__main__":
    main()
