#!/usr/bin/env python3
"""Generate a vasm LVO include (_LVOName equ -offset) from an Amiga .fd file.

The Commodore NDK 3.1 has .fd files but no lvo/*.i includes (NDK 3.2 has
both).  Private functions take an offset too, so they are counted.

usage: fd2lvo.py input.fd output.i
"""
import re
import sys


def main():
    src, dst = sys.argv[1], sys.argv[2]
    offset = 30
    out = []
    for raw in open(src, encoding="latin-1"):
        line = raw.strip()
        if not line or line.startswith("*"):
            continue
        if line.startswith("##"):
            key, _, arg = line[2:].partition(" ")
            if key == "bias":
                offset = int(arg)
            elif key == "end":
                break
            continue
        m = re.match(r"([A-Za-z_][A-Za-z0-9_]*)\s*\(", line)
        if not m:
            continue
        out.append(f"_LVO{m.group(1)}\tequ\t-{offset}\n")
        offset += 6
    with open(dst, "w") as f:
        f.write(f"; generated by tools/fd2lvo.py from {src.split('/')[-1]} - do not edit\n")
        f.writelines(out)


if __name__ == "__main__":
    main()
